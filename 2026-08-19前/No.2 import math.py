# 作用：导入数学库，提供 sqrt 等数学函数
import math #这是数学函数的代码，如果不加函数就用不了
# 作用：给变量 a、b、c 赋值，它们是二次方程 ax² + bx + c = 0 的系数
a=-1
b=-2
c=3
# 作用：用求根公式算第一个解；math.sqrt 是开平方根，** 表示乘方
x = (-b + math.sqrt(b ** 2 - 4 * a * c))/(2 * a)
# 复习：第二个解也来自求根公式，只是正负号不同
# 注意：这里的 ** 1/2 实际是先乘方再除以 2，不是开平方；想开平方应使用 math.sqrt
y = (-b - (b ** 2 - 4 * a * c) ** 1/2)/(2 * a)
# 复习：print 把变量值显示到屏幕上
print(x)
print(y)
